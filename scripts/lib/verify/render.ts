/**
 * Renders the generated Verify workflows: the top-level `verify.yaml` and one reusable workflow per
 * shard, each holding the jobs of a group of targets.
 *
 * The generator changes a source job in exactly two ways, so what a reader sees in a source is what
 * runs: it gates the job on the target being selected, and it prefixes the job's display name with
 * the target's title. Everything else, `inputs.*` references included, is written by the source.
 *
 * @packageDocumentation
 */

/** Repository-relative path of the top-level workflow. */
export const VERIFY_WORKFLOW = '.github/workflows/verify.yaml';

/** The first line of every file this generator writes, which also marks a file as its own. */
export const GENERATED_HEADER = '# GENERATED by scripts/generate-verify.ts. Do not edit by hand.';

/** Display name of the final job: the check branch protection requires. */
export const SUMMARY_JOB_NAME = 'CI Summary: Verify';

/** Job id of the final job. */
export const SUMMARY_JOB_ID = 'verify';

/** Job ids of `verify.yaml` a source may not use, so ids stay unique across every generated file. */
export const RESERVED_JOB_IDS: readonly string[] = ['plan', 'install', 'build', SUMMARY_JOB_ID];

/** Prefix of every shard id: `verify-<category>` and `verify-<category>-<n>`. */
export const SHARD_PREFIX = 'verify-';

/**
 * A shard is split once its jobs pass this size. Comfortably below the 500 KB GitHub refuses to start
 * a workflow above, so a target that grows does not take its shard over the limit on its own.
 */
export const SHARD_SIZE_BUDGET = 300_000;

/** The `if:` gate prepended to every job of a target. */
export function targetGate(target: string): string {
  return `contains(fromJSON(inputs.targets), '${target}')`;
}

/** One target's jobs, ready to place in a shard. */
export interface RenderedTarget {
  readonly source: VerifySource;
  /** The jobs as text, indented to sit under a `jobs:` key, gated and named. */
  readonly text: string;
  /** The jobs as parsed back from {@link text}, in order. */
  readonly jobs: readonly Record<string, unknown>[];
  /** The job ids, in order. */
  readonly jobIds: readonly string[];
  /** Rendered size of the jobs, for shard packing. */
  readonly size: number;
}

/** One generated reusable workflow. */
export interface Shard {
  /** `verify-<category>` or `verify-<category>-<n>`; also its caller job id in `verify.yaml`. */
  readonly id: string;
  /** Display name of its caller job in `verify.yaml`. */
  readonly title: string;
  readonly targets: readonly RenderedTarget[];
}

/** The workflow file of a shard. */
export function shardFile(shardId: string): string {
  return `.github/workflows/${shardId}.yaml`;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** A condition with its `${{ }}` wrapper removed. */
function unwrapExpression(raw: string, where: string): string {
  const trimmed = raw.trim();
  const wrapped = /^\$\{\{([\s\S]*)\}\}$/.exec(trimmed);
  const expression = (wrapped?.[1] ?? trimmed).trim();
  if (expression.includes('${{')) {
    throw new Error(`${where}: write the if: condition as one expression, not as text with several \${{ }} parts.`);
  }

  return expression;
}

/** A YAML single-quoted scalar: the one quoting that needs no escape but a doubled quote. */
function singleQuoted(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

const JOB_HEADER = /^ {2}([A-Za-z_][\w-]*):\s*(?:#.*)?$/;

/**
 * The text of the `jobs:` block of a source, without the `jobs:` line: every line after it up to the
 * next top-level key. Comments and blank lines are kept, so the generated workflow reads like the
 * source.
 */
export function jobsBlock(text: string): string[] {
  const lines = text.replaceAll('\r\n', '\n').split('\n');
  const start = lines.findIndex((line) => /^jobs:\s*(?:#.*)?$/.test(line));
  if (start === -1) {
    return [];
  }
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((line) => line !== '' && !line.startsWith(' ') && !line.startsWith('#'));
  const block = end === -1 ? rest : rest.slice(0, end);
  while (block.length > 0 && (block.at(-1)?.trim() ?? '') === '') {
    block.pop();
  }

  return block;
}

/** The line ranges of the jobs in a jobs block, in order. */
function jobRanges(lines: readonly string[]): { id: string; start: number; end: number }[] {
  const starts = lines.flatMap((line, index) => {
    const match = JOB_HEADER.exec(line);
    return match ? [{ id: match[1], start: index }] : [];
  });

  return starts.map(({ id, start }, index) => ({ id, start, end: starts[index + 1]?.start ?? lines.length }));
}

/** The index of a job-level key's line within a job's lines, or -1. */
function keyLine(job: readonly string[], key: string): number {
  return job.findIndex((line) => line.startsWith(`    ${key}:`));
}

/**
 * Gates one job on its target and prefixes its display name. An existing condition is kept in
 * parentheses after the gate, so `always()` keeps letting the job run after a failed dependency.
 *
 * Line based, so every other line of the job, comments and block scalars included, is copied as
 * written. The caller re-parses the result and checks both values.
 */
function gateAndName(job: readonly string[], id: string, value: Record<string, unknown>, source: VerifySource): string[] {
  const where = `${source.file} job ${id}`;
  const name = value['name'];
  const displayName = `${source.title}: ${typeof name === 'string' ? name : id}`;
  const original = value['if'];
  if (original !== undefined && typeof original !== 'string' && typeof original !== 'boolean') {
    throw new Error(`${where}: if: must be a string.`);
  }
  const gate = targetGate(source.target);
  const condition = original === undefined ? gate : `${gate} && (${unwrapExpression(String(original), where)})`;

  const lines = [...job];
  for (const key of ['name', 'if']) {
    const at = keyLine(lines, key);
    if (at !== -1 && (/:\s*[>|]/.test(lines[at]) || (lines[at + 1] ?? '').startsWith('      '))) {
      throw new Error(`${where}: write ${key}: on one line.`);
    }
  }
  const nameLine = `    name: ${singleQuoted(displayName)}`;
  const ifLine = `    if: \${{ ${condition} }}`;
  const nameAt = keyLine(lines, 'name');
  if (nameAt === -1) {
    lines.splice(1, 0, nameLine);
  } else {
    lines[nameAt] = nameLine;
  }
  const ifAt = keyLine(lines, 'if');
  if (ifAt === -1) {
    lines.splice(keyLine(lines, 'name') + 1, 0, ifLine);
  } else {
    lines[ifAt] = ifLine;
  }

  return lines;
}

/**
 * Renders one target's jobs: the generated end-to-end job first when the source has an `e2e` block,
 * then the source's own jobs, each gated and named.
 *
 * @param builds - whether the target runs a bundle, so its end-to-end job installs the build artifact
 * @throws an `Error` when the rendered jobs do not parse back to the source's jobs plus the two edits
 */
export function renderTarget(source: VerifySource, builds: boolean, modulePaths: readonly string[]): RenderedTarget {
  const generated = source.e2e === undefined ? [] : e2eJob(source, builds, modulePaths).trimEnd().split('\n');
  const sourceLines = jobsBlock(source.text);
  const block = [...generated, ...(generated.length > 0 && sourceLines.length > 0 ? [''] : []), ...sourceLines];
  const parsedSource = (parseDocument(`jobs:\n${block.join('\n')}\n`).toJS() as { jobs?: Record<string, Record<string, unknown>> })
    .jobs ?? {};

  const ranges = jobRanges(block);
  const output: string[] = [];
  let cursor = 0;
  for (const { id, start, end } of ranges) {
    output.push(...block.slice(cursor, start));
    output.push(...gateAndName(block.slice(start, end), id, parsedSource[id] ?? {}, source));
    cursor = end;
  }
  output.push(...block.slice(cursor));
  const text = `${output.join('\n')}\n`;

  const parsed = (parseDocument(`jobs:\n${text}`).toJS() as { jobs?: Record<string, Record<string, unknown>> }).jobs ?? {};
  const jobIds = ranges.map((range) => range.id);
  const expectedIds = [...(source.e2e === undefined ? [] : [e2eJobId(source.target)]), ...source.jobIds];
  if (JSON.stringify(Object.keys(parsed)) !== JSON.stringify(expectedIds) || JSON.stringify(jobIds) !== JSON.stringify(expectedIds)) {
    throw new Error(`${source.file}: the jobs block could not be split into its jobs; keep job keys at two spaces.`);
  }
  for (const id of jobIds) {
    const { name: _name, if: _if, ...rest } = parsed[id];
    const { name: _sourceName, if: _sourceIf, ...sourceRest } = parsedSource[id];
    if (JSON.stringify(rest) !== JSON.stringify(sourceRest) || typeof parsed[id]['if'] !== 'string') {
      throw new Error(`${source.file} job ${id}: rendering changed more than its name and if; keep job keys at four spaces.`);
    }
  }

  return { source, text, jobIds, jobs: jobIds.map((id) => parsed[id]), size: Buffer.byteLength(text) };
}

/** Title-cases one path segment. */
function titleCase(segment: string): string {
  return segment.charAt(0).toUpperCase() + segment.slice(1);
}

/**
 * Groups targets into shards: one per category, split into `-2`, `-3`… in target order once a shard's
 * jobs pass `budget` bytes.
 *
 * @throws an `Error` for a single target whose jobs alone exceed the budget
 */
export function assignShards(targets: readonly RenderedTarget[], budget = SHARD_SIZE_BUDGET): Shard[] {
  const shards: { id: string; title: string; targets: RenderedTarget[]; size: number }[] = [];
  const sorted = [...targets].sort((a, b) => a.source.target.localeCompare(b.source.target));

  for (const target of sorted) {
    if (target.size > budget) {
      throw new Error(
        `${target.source.file}: its jobs render to ${target.size} bytes, over the ${budget}-byte shard budget. ` +
          'Split the target.',
      );
    }
    const category = target.source.target.split('/')[0];
    const own = shards.filter((shard) => shard.id === `${SHARD_PREFIX}${category}` || shard.id.startsWith(`${SHARD_PREFIX}${category}-`));
    const current = own.at(-1);
    if (current !== undefined && current.size + target.size <= budget) {
      current.targets.push(target);
      current.size += target.size;
      continue;
    }
    const number = own.length + 1;
    shards.push({
      id: number === 1 ? `${SHARD_PREFIX}${category}` : `${SHARD_PREFIX}${category}-${number}`,
      title: number === 1 ? titleCase(category) : `${titleCase(category)} ${number}`,
      targets: [target],
      size: target.size,
    });
  }

  return shards.map(({ id, title, targets: members }) => ({ id, title, targets: members }));
}

type Access = 'read' | 'write' | 'none';
const ACCESS_RANK: Readonly<Record<Access, number>> = { none: 0, read: 1, write: 2 };

/**
 * The union of the job permissions of a shard. A called workflow's token can only be narrowed, never
 * widened, so its caller job has to grant everything any of its jobs asks for.
 */
export function shardPermissions(shard: Shard): Record<string, Access> {
  const union: Record<string, Access> = {};
  for (const target of shard.targets) {
    for (const [index, job] of target.jobs.entries()) {
      const where = `${target.source.file} job ${target.jobIds[index]}`;
      const block = job['permissions'];
      if (!isRecord(block)) {
        throw new Error(`${where} must declare its permissions as a mapping.`);
      }
      for (const [scope, access] of Object.entries(block)) {
        if (access !== 'read' && access !== 'write' && access !== 'none') {
          throw new Error(`${where}: permission ${scope} is ${String(access)}.`);
        }
        if (ACCESS_RANK[access] > ACCESS_RANK[union[scope] ?? 'none']) {
          union[scope] = access;
        }
      }
    }
  }

  return Object.fromEntries(Object.entries(union).sort(([a], [b]) => a.localeCompare(b)));
}

/** The repository secrets a shard's jobs read, which the caller passes on by name. */
export function shardSecrets(text: string): string[] {
  const names = [...text.matchAll(/\bsecrets\.([A-Za-z_]\w*)/g)].map((match) => match[1]);

  return [...new Set(names)].filter((name) => name !== 'GITHUB_TOKEN').sort();
}

/** Renders a shard's reusable workflow, before formatting. */
export function renderShard(shard: Shard): string {
  const resolved = resolvePins(`jobs:\n${shard.targets.map((target) => target.text).join('\n')}`);
  const secrets = shardSecrets(resolved);
  const targets = shard.targets.map((target) => `#   ${target.source.target} (${target.source.file})`).join('\n');
  const secretBlock =
    secrets.length === 0
      ? ''
      : `    secrets:\n${secrets.map((name) => `      ${name}:\n        required: false`).join('\n')}\n`;

  return `${GENERATED_HEADER}
# Run 'bun run generate-verify' to rebuild it from the sources in .github/verify/; the drift check in
# Scripts CI fails while it is out of date. See docs/verify-pipeline.md.
#
# Called by .github/workflows/verify.yaml. Every job runs only when its target is in inputs.targets.
# Targets:
${targets}
name: Verify ${shard.title}

on:
  workflow_call:
    inputs:
      targets:
        description: JSON array of the targets this run verifies.
        type: string
        required: true
      cache-key:
        description: Key of the dependency cache the install job saved.
        type: string
        required: false
        default: ''
      artifact-id:
        description: ID of the artifact the build job uploaded; empty when nothing was built.
        type: string
        required: false
        default: ''
      manifest-sha256:
        description: SHA-256 of the build manifest inside that artifact.
        type: string
        required: false
        default: ''
${secretBlock}
permissions: {}

${resolved}`;
}

/** Renders `verify.yaml`, before formatting. */
export function renderVerifyWorkflow(
  shards: readonly Shard[],
  modulePaths: readonly string[],
  secretsByShard: ReadonlyMap<string, readonly string[]>,
): string {
  const callers = shards
    .map((shard) => {
      const permissions = shardPermissions(shard);
      const permissionLines = Object.entries(permissions).map(([scope, access]) => `      ${scope}: ${access}`);
      const secrets = secretsByShard.get(shard.id) ?? [];

      return `  ${shard.id}:
    name: ${shard.title}
    needs: [plan, install, build]
    # Runs once the shared build succeeded, or was skipped because none of the selected targets
    # runs a bundle.
    if: \${{ !cancelled() && needs.install.result == 'success' && (needs.build.result == 'success' || needs.build.result == 'skipped') && contains(fromJSON(needs.plan.outputs.shards), '${shard.id}') }}
    uses: ./${shardFile(shard.id)}
    permissions:${permissionLines.length === 0 ? ' {}' : `\n${permissionLines.join('\n')}`}
    with:
      targets: \${{ needs.plan.outputs.targets }}
      cache-key: \${{ needs.install.outputs.cache-key }}
      artifact-id: \${{ needs.build.outputs.artifact-id }}
      manifest-sha256: \${{ needs.build.outputs.manifest-sha256 }}${
        secrets.length === 0
          ? ''
          : `\n    secrets:\n${secrets.map((name) => `      ${name}: \${{ secrets.${name} }}`).join('\n')}`
      }
`;
    })
    .join('\n');
  const needs = ['plan', 'install', 'build', ...shards.map((shard) => shard.id)].map((id) => `      - ${id}`).join('\n');

  return `${GENERATED_HEADER}
# Run 'bun run generate-verify' to rebuild it from the sources in .github/verify/; the drift check in
# Scripts CI fails while it is out of date. See docs/verify-pipeline.md.
#
# One run verifies every target the change affects: plan selects them from the changed files and the
# dependency graph, install and build run once for all of them, and each shard runs the jobs of its
# selected targets. The final job is the one required check.
name: Verify

on:
  pull_request:
  push:
    branches:
      - main
      - 'feature/**'
  workflow_dispatch:
  schedule:
    - cron: '17 5 * * 1'

concurrency:
  group: \${{ github.workflow }}-\${{ github.ref }}
  cancel-in-progress: true

permissions: {}

jobs:
${planJob()}
${installJob(modulePaths)}
${buildJob(modulePaths)}
${callers}
  ${SUMMARY_JOB_ID}:
    name: '${SUMMARY_JOB_NAME}'
    if: \${{ always() }}
    needs:
${needs}
    runs-on: ubuntu-latest
    timeout-minutes: 5
    permissions: {}
    steps:
      - name: Fail if any verify job did not succeed
        if: \${{ contains(needs.*.result, 'failure') || contains(needs.*.result, 'cancelled') }}
        run: exit 1
`;
}

/** The `uses:` values that install the shared build's artifact. */
function isInstallStep(uses: string): boolean {
  return uses === 'pinned:installBuiltActions' || uses === PINNED.installBuiltActions.split(' ')[0];
}

/** The action directory a local `uses:` names, with any checkout prefix removed. */
function localAction(uses: string): string | undefined {
  const local = localUsesPath(uses);
  if (local === undefined) {
    return undefined;
  }
  const prefix = CHECKOUT_PREFIXES.find((candidate) => local.startsWith(`${candidate}/`));

  return prefix === undefined ? local : local.slice(prefix.length + 1);
}

/** The variables of the generated workflows that a source may not reach around. */
const RESERVED_NEEDS = /\bneeds\.(?:plan|install|build)(?![\w-])/;

/**
 * Checks the rules every source job follows, across all targets, so a mistake fails the generator
 * rather than a runner:
 *
 * - job ids are unique across every target, and none is a job id of `verify.yaml`
 * - a job needs only jobs of its own target
 * - a job declares its permissions as a mapping
 * - a job reads the shared build through `inputs.*`, never through `needs.plan|install|build`
 * - a job that runs a local action with a bundle installs the build artifact in an earlier step, and
 *   lets that download through its egress allowlist
 *
 * @param root - absolute path of the repository root, to read action manifests
 * @throws an `Error` listing every problem found
 */
export function validateSources(root: string, sources: readonly VerifySource[]): void {
  const problems: string[] = [];
  const owners = new Map<string, string>();
  const bundled = new Map<string, boolean>();
  const hasBundle = (action: string): boolean => {
    if (!bundled.has(action)) {
      let result = false;
      try {
        result = buildSet(root, [action]).bundles.length > 0;
      } catch {
        result = false;
      }
      bundled.set(action, result);
    }
    return bundled.get(action) === true;
  };

  for (const source of sources) {
    const ids = [...(source.e2e === undefined ? [] : [e2eJobId(source.target)]), ...source.jobIds];
    for (const id of ids) {
      if (RESERVED_JOB_IDS.includes(id)) {
        problems.push(`${source.file}: job id ${id} is reserved for verify.yaml.`);
      }
      const owner = owners.get(id);
      if (owner !== undefined) {
        problems.push(`${source.file}: job id ${id} is also used by ${owner}; job ids must be unique across targets.`);
      }
      owners.set(id, source.file);
    }

    for (const id of source.jobIds) {
      const where = `${source.file} job ${id}`;
      const job = jobValue(source, id);
      const needs = typeof job['needs'] === 'string' ? [job['needs']] : Array.isArray(job['needs']) ? job['needs'] : [];
      for (const need of needs) {
        if (!ids.includes(String(need))) {
          problems.push(`${where}: needs ${String(need)}, which is not a job of ${source.target}.`);
        }
      }
      if (!isRecord(job['permissions'])) {
        problems.push(`${where}: declare permissions as a mapping; a called workflow has no default to inherit.`);
      }
      const text = JSON.stringify(job);
      if (RESERVED_NEEDS.test(text)) {
        problems.push(`${where}: read the shared build through inputs.artifact-id, inputs.manifest-sha256 and inputs.cache-key.`);
      }

      const steps = Array.isArray(job['steps']) ? (job['steps'] as unknown[]) : [];
      const uses = steps.map((step) => (isRecord(step) && typeof step['uses'] === 'string' ? step['uses'] : ''));
      const firstInstall = uses.findIndex(isInstallStep);
      const firstBundled = uses.findIndex((value) => {
        const action = localAction(value);
        return action !== undefined && action.startsWith('actions/') && hasBundle(action);
      });
      if (firstBundled !== -1 && (firstInstall === -1 || firstInstall > firstBundled)) {
        problems.push(`${where}: runs ${uses[firstBundled]} without installing the built actions first.`);
      }
      if (firstInstall !== -1) {
        const allowlist = steps
          .map((step) => (isRecord(step) && isRecord(step['with']) ? step['with']['allowed-endpoints'] : undefined))
          .find((value): value is string => typeof value === 'string');
        const missing = allowlist === undefined ? [] : ARTIFACT_ENDPOINTS.filter((host) => !allowlist.includes(host));
        if (missing.length > 0) {
          problems.push(`${where}: installs the built actions but its allowlist lacks ${missing.join(', ')}.`);
        }
      }
    }
  }

  if (problems.length > 0) {
    throw new Error(`The Verify sources break the contract:\n${problems.map((problem) => `  - ${problem}`).join('\n')}`);
  }
}
