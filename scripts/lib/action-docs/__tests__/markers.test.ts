import { describe, expect, it } from 'vitest';

import { findRegions, MarkerError, newReadme, REGION_NAMES, spliceRegions } from '../markers.js';

import type { Regions } from '../markers.js';

const FILE = 'actions/x/y/README.md';

function regions(overrides: Partial<Regions> = {}): Regions {
  const base = Object.fromEntries(REGION_NAMES.map((name) => [name, `${name} content`])) as Regions;
  return { ...base, ...overrides };
}

describe('newReadme', () => {
  it('lays out the banner and every region in order', () => {
    const readme = newReadme(regions());
    expect(findRegions(readme, FILE)).toEqual([...REGION_NAMES]);
    expect(readme.startsWith('<!--\nGenerated by `bun run generate-docs`')).toBe(true);
    expect(readme).toContain('<!-- docs:generated inputs -->\ninputs content\n<!-- /docs:generated inputs -->');
    expect(readme.endsWith('<!-- /docs:generated reference -->\n')).toBe(true);
  });

  it('keeps an empty region as two adjacent markers', () => {
    expect(newReadme(regions({ egress: '' }))).toContain(
      '<!-- docs:generated egress -->\n<!-- /docs:generated egress -->',
    );
  });
});

describe('spliceRegions', () => {
  const existing = [
    '<!-- docs:generated header -->',
    'old header',
    '<!-- /docs:generated header -->',
    '',
    'Prose the author wrote, kept verbatim.',
    '',
    '<!-- docs:generated inputs -->',
    'old',
    'inputs',
    '<!-- /docs:generated inputs -->',
    '',
    '## Behaviour',
    '',
    'More prose.',
    '',
  ].join('\n');

  it('rewrites the regions present and leaves every other line alone', () => {
    expect(spliceRegions(existing, regions(), FILE)).toBe(
      [
        '<!-- docs:generated header -->',
        'header content',
        '<!-- /docs:generated header -->',
        '',
        'Prose the author wrote, kept verbatim.',
        '',
        '<!-- docs:generated inputs -->',
        'inputs content',
        '<!-- /docs:generated inputs -->',
        '',
        '## Behaviour',
        '',
        'More prose.',
        '',
      ].join('\n'),
    );
  });

  it('does not add a region the file does not carry', () => {
    expect(spliceRegions(existing, regions(), FILE)).not.toContain('egress');
  });

  it('is stable when run again', () => {
    const once = spliceRegions(existing, regions(), FILE);
    expect(spliceRegions(once, regions(), FILE)).toBe(once);
  });

  it('leaves a file without markers unchanged', () => {
    expect(spliceRegions('# Title\n\nJust prose.\n', regions(), FILE)).toBe('# Title\n\nJust prose.\n');
  });

  it('treats a marker inside a code block as text', () => {
    const readme = [
      'Mark a region like this:',
      '',
      '```markdown',
      '<!-- docs:generated inputs -->',
      '<!-- /docs:generated nope -->',
      '```',
      '',
      '<!-- docs:generated header -->',
      'old',
      '<!-- /docs:generated header -->',
      '',
    ].join('\n');

    expect(findRegions(readme, FILE)).toEqual(['header']);
    expect(spliceRegions(readme, regions(), FILE)).toContain(
      '```markdown\n<!-- docs:generated inputs -->\n<!-- /docs:generated nope -->\n```',
    );
  });
});

describe('marker errors', () => {
  it.each([
    ['an unknown region', '<!-- docs:generated nope -->\n<!-- /docs:generated nope -->', /:1: unknown region 'nope'/],
    [
      'a region opened twice',
      '<!-- docs:generated inputs -->\n<!-- /docs:generated inputs -->\n<!-- docs:generated inputs -->\n<!-- /docs:generated inputs -->',
      /:3: region 'inputs' appears twice/,
    ],
    [
      'a nested region',
      '<!-- docs:generated inputs -->\n<!-- docs:generated outputs -->',
      /:2: region 'outputs' opens inside region 'inputs'/,
    ],
    ['a close without an open', 'x\n<!-- /docs:generated inputs -->', /:2: region 'inputs' closes without being open/],
    [
      'a close for another region',
      '<!-- docs:generated inputs -->\n<!-- /docs:generated outputs -->',
      /:2: region 'outputs' closes without being open/,
    ],
    ['an unclosed region', 'a\n<!-- docs:generated inputs -->\nb', /:2: region 'inputs' is never closed/],
  ])('refuses %s', (_case, readme, message) => {
    expect(() => spliceRegions(readme, regions(), FILE)).toThrow(MarkerError);
    expect(() => findRegions(readme, FILE)).toThrow(message);
  });
});
