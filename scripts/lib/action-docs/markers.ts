/**
 * The marked regions of an action README.
 *
 * Text between `<!-- docs:generated NAME -->` and `<!-- /docs:generated NAME -->` is rewritten on
 * every run; everything outside is prose and is never touched. Each marker sits on a line of its
 * own, which keeps the rule simple enough that an author can see at a glance what is theirs.
 */

/** Every region, in the order a new README lays them out. */
export const REGION_NAMES = ['header', 'usage', 'inputs', 'outputs', 'permissions', 'egress', 'reference'] as const;
export type RegionName = (typeof REGION_NAMES)[number];
export type Regions = Readonly<Record<RegionName, string>>;

const MARKER = /^<!-- (\/?)docs:generated ([a-z-]+) -->$/;

const BANNER = `<!--
Generated by \`bun run generate-docs\` from action.yaml and docs.yaml. Text between docs:generated
markers is rewritten on every run, and the update-files workflow commits the result. Write prose
outside the markers.
-->`;

export class MarkerError extends Error {
  constructor(file: string, line: number, message: string) {
    super(`${file}:${line}: ${message}`);
    this.name = 'MarkerError';
  }
}

function openMarker(name: RegionName): string {
  return `<!-- docs:generated ${name} -->`;
}

function closeMarker(name: RegionName): string {
  return `<!-- /docs:generated ${name} -->`;
}

function block(name: RegionName, content: string): string[] {
  const body = content.trim();
  return [openMarker(name), ...(body ? body.split('\n') : []), closeMarker(name)];
}

function isRegionName(name: string): name is RegionName {
  return (REGION_NAMES as readonly string[]).includes(name);
}

/** The region names a README carries, in file order. Throws on malformed markers. */
export function findRegions(readme: string, file: string): RegionName[] {
  return scan(readme, file).regions;
}

interface Scan {
  regions: RegionName[];
  /** For each region, the indexes of its open and close marker lines. */
  spans: Map<RegionName, { open: number; close: number }>;
  lines: string[];
}

/** A marker line, parsed. `undefined` for any other line. */
function parseMarker(
  line: string,
  file: string,
  lineNumber: number,
): { name: RegionName; closes: boolean } | undefined {
  const match = MARKER.exec(line.trim());
  if (!match) {
    return undefined;
  }
  const [, slash, name] = match;
  if (!isRegionName(name)) {
    throw new MarkerError(file, lineNumber, `unknown region '${name}', expected one of ${REGION_NAMES.join(', ')}`);
  }
  return { name, closes: slash === '/' };
}

function isFenceLine(line: string): boolean {
  const trimmed = line.trimStart();
  return trimmed.startsWith('```') || trimmed.startsWith('~~~');
}

/** Every marker line outside a code block, with its 0-based line index. */
function markerLines(lines: readonly string[], file: string): { index: number; name: RegionName; closes: boolean }[] {
  const markers: { index: number; name: RegionName; closes: boolean }[] = [];
  let inFence = false;
  for (const [index, line] of lines.entries()) {
    // A marker shown inside a code block, as in docs about this generator, is text, not a marker.
    if (isFenceLine(line)) {
      inFence = !inFence;
    }
    const marker = inFence ? undefined : parseMarker(line, file, index + 1);
    if (marker) {
      markers.push({ index, ...marker });
    }
  }
  return markers;
}

function scan(readme: string, file: string): Scan {
  const lines = readme.split('\n');
  const spans = new Map<RegionName, { open: number; close: number }>();
  const regions: RegionName[] = [];
  let current: { name: RegionName; open: number } | undefined;

  for (const marker of markerLines(lines, file)) {
    const { index, name } = marker;

    if (marker.closes) {
      if (current?.name !== name) {
        throw new MarkerError(file, index + 1, `region '${name}' closes without being open`);
      }
      spans.set(name, { open: current.open, close: index });
      regions.push(name);
      current = undefined;
      continue;
    }
    if (current) {
      throw new MarkerError(file, index + 1, `region '${name}' opens inside region '${current.name}'`);
    }
    if (spans.has(name)) {
      throw new MarkerError(file, index + 1, `region '${name}' appears twice`);
    }
    current = { name, open: index };
  }

  if (current) {
    throw new MarkerError(file, current.open + 1, `region '${current.name}' is never closed`);
  }
  return { regions, spans, lines };
}

/**
 * Rewrites the regions an existing README carries and leaves every other line as it was.
 *
 * A region the file does not carry is not added: where it belongs among the prose is the author's
 * decision. Running this twice gives the same file.
 */
export function spliceRegions(readme: string, regions: Regions, file: string): string {
  const { spans, lines } = scan(readme, file);
  const ordered = [...spans.entries()].sort((a, b) => a[1].open - b[1].open);

  const output: string[] = [];
  let cursor = 0;
  for (const [name, span] of ordered) {
    output.push(...lines.slice(cursor, span.open), ...block(name, regions[name]));
    cursor = span.close + 1;
  }
  output.push(...lines.slice(cursor));
  return output.join('\n');
}

/** A complete README for an action that has none yet: the banner and every region, in order. */
export function newReadme(regions: Regions): string {
  const parts = [BANNER, ...REGION_NAMES.map((name) => block(name, regions[name]).join('\n'))];
  return `${parts.join('\n\n')}\n`;
}
